function ExternalLink({ href, children }: { href: string; children: React.ReactNode }) {
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      onClick={e => {
        e.preventDefault()
        if (typeof chrome !== "undefined" && chrome.tabs) {
          chrome.tabs.create({ url: href })
        } else {
          window.open(href, "_blank")
        }
      }}
    >
      {children}
    </a>
  )
}

